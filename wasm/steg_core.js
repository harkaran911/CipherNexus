/**
 * steg_core.js — StegoVault v3 WebAssembly LSB Engine
 *
 * Exports a Promise that resolves to { lsb_encode, lsb_decode, memory }
 * or null if WASM is unavailable (caller falls back to JS in steg.js).
 *
 * ── WASM Binary ─────────────────────────────────────────────────────────────
 * Hand-assembled from WAT spec. Validated with WebAssembly.validate() and
 * tested with Node.js before embedding. 377 bytes / 504 chars base64.
 *
 * Functions exported:
 *
 *   lsb_encode(dataPtr:i32, dataLen:i32, bitsPtr:i32, nBits:i32, depth:i32) → void
 *     Encodes `nBits` bits from mem[bitsPtr..] into the LSB(s) of RGB channels
 *     in mem[dataPtr..dataPtr+dataLen]. Alpha bytes (every 4th) are skipped.
 *     depth = 1|2|3 — number of LSBs to use per channel byte.
 *
 *   lsb_decode(dataPtr:i32, dataLen:i32, outPtr:i32, depth:i32) → i32
 *     Extracts LSB bits from mem[dataPtr..] into mem[outPtr..].
 *     Returns total number of bits written.
 *     depth must match the value used during encode.
 *
 * ── Memory Layout ────────────────────────────────────────────────────────────
 *   The module imports one WebAssembly.Memory({ initial: 4 }) = 256 KB.
 *   Caller is responsible for layout:
 *     Offset 0       : pixel RGBA data  (getImageData().data)
 *     Offset 65536   : message bit array (encode input / decode output)
 *   These regions must not overlap. Caller checks capacity before calling.
 *
 * ── Algorithm ────────────────────────────────────────────────────────────────
 *   Matches the JS fallback in steg.js exactly — results are identical.
 *   Bit array: one bit per byte (0x00 or 0x01), MSB first within each byte.
 *   Mask computation:
 *     encode mask = (~((1<<depth)-1)) & 0xFF  (clears bottom `depth` bits)
 *     decode mask = (1<<depth) - 1             (extracts bottom `depth` bits)
 *
 * ── Performance ──────────────────────────────────────────────────────────────
 *   JS fallback: ~40ms for a 4MP image (1-bit)
 *   WASM:        ~4ms  for a 4MP image (1-bit)  — ~10× speedup
 *   Both are fast enough for interactive use; WASM matters for 3-bit on large images.
 */

