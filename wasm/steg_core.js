// ── Memory config ─────────────────────────────────────────────────────────────
export const WASM_PAGES = 4; // 4 × 64KB = 256KB
export const DATA_OFFSET = 0; // pixel RGBA data starts here
export const BITS_OFFSET = 65536; // bit array starts at page 2
export const MAX_PIXEL_BYTES = 65536; // max RGBA data = 64KB (128×128 px)
// For larger images, caller tiles or uses JS

// ── Module initialisation ─────────────────────────────────────────────────────
let _wasmExports = null;
let _wasmMemory = null;
let _initPromise = null;

/**
 * initWasm() — loads and compiles the WASM module once.
 * Returns Promise<{ lsb_encode, lsb_decode, memory, memBytes }> or null.
 * Safe to call multiple times — subsequent calls return the cached promise.
 */
export function initWasm() {
  if (_initPromise) return _initPromise;

  _initPromise = (async () => {
    try {
      // Decode base64 → Uint8Array
      const binaryStr = atob(WASM_BASE64);
      const binary = new Uint8Array(binaryStr.length);
      for (let i = 0; i < binaryStr.length; i++)
        binary[i] = binaryStr.charCodeAt(i);

      // Quick integrity check before compiling
      if (
        binary[0] !== 0x00 ||
        binary[1] !== 0x61 ||
        binary[2] !== 0x73 ||
        binary[3] !== 0x6d
      ) {
        throw new Error("WASM magic bytes corrupted");
      }

      _wasmMemory = new WebAssembly.Memory({ initial: WASM_PAGES });

      const { instance } = await WebAssembly.instantiate(binary, {
        env: { memory: _wasmMemory },
      });

      _wasmExports = instance.exports;

      // Verify expected exports exist
      if (
        typeof _wasmExports.lsb_encode !== "function" ||
        typeof _wasmExports.lsb_decode !== "function"
      ) {
        throw new Error("WASM exports missing");
      }

      console.info(
        "%c[StegoVault WASM] LSB engine loaded ✓ " +
          "(377 bytes, lsb_encode + lsb_decode)",
        "color:#6ee7b7;font-weight:bold",
      );

      return {
        lsb_encode: _wasmExports.lsb_encode,
        lsb_decode: _wasmExports.lsb_decode,
        memory: _wasmMemory,
        memBytes: new Uint8Array(_wasmMemory.buffer),
      };
    } catch (err) {
      console.warn(
        "[StegoVault WASM] Failed to load — JS fallback active:",
        err.message,
      );
      _initPromise = null; // allow retry
      return null;
    }
  })();

  return _initPromise;
}

// ── High-level helpers ────────────────────────────────────────────────────────
/**
 * wasmEncode(pixelData, msgBits, depth) → Uint8Array (modified pixel data)
 *
 * pixelData : Uint8ClampedArray — from ctx.getImageData().data
 * msgBits   : Uint8Array        — one bit per byte (0|1), MSB first
 * depth     : 1 | 2 | 3
 *
 * Returns a new Uint8Array with the message encoded, or null if WASM unavailable.
 * For images where pixelData.length > MAX_PIXEL_BYTES, returns null (use JS fallback).
 */
export async function wasmEncode(pixelData, msgBits, depth) {
  if (pixelData.length > MAX_PIXEL_BYTES) return null; // too big for single WASM page

  const wasm = await initWasm();
  if (!wasm) return null;

  const mem = new Uint8Array(wasm.memory.buffer);

  // Copy pixel data into WASM memory at DATA_OFFSET
  mem.set(pixelData, DATA_OFFSET);

  // Copy message bits into WASM memory at BITS_OFFSET
  const nBits = msgBits.length;
  mem.set(msgBits, BITS_OFFSET);

  // Run WASM encode
  wasm.lsb_encode(DATA_OFFSET, pixelData.length, BITS_OFFSET, nBits, depth);

  // Return modified pixel data
  return new Uint8Array(wasm.memory.buffer, DATA_OFFSET, pixelData.length);
}

/**
 * wasmDecode(pixelData, depth) → Uint8Array (bit array: one bit per byte)
 *
 * Returns the full bit array extracted from LSBs, or null if WASM unavailable.
 * Caller scans for null byte (8 zero bits) to find message end.
 */
export async function wasmDecode(pixelData, depth) {
  if (pixelData.length > MAX_PIXEL_BYTES) return null;

  const wasm = await initWasm();
  if (!wasm) return null;

  const mem = new Uint8Array(wasm.memory.buffer);
  mem.set(pixelData, DATA_OFFSET);

  const nBitsWritten = wasm.lsb_decode(
    DATA_OFFSET,
    pixelData.length,
    BITS_OFFSET,
    depth,
  );

  return new Uint8Array(wasm.memory.buffer, BITS_OFFSET, nBitsWritten);
}

// ── Status ───────────────────────────────────────────────────────────────────
/** Returns true if WASM is loaded and ready. */
export function isWasmReady() {
  return _wasmExports !== null;
}

// Kick off initialisation immediately on module load
initWasm();
